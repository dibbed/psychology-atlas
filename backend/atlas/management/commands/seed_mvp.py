class Command(BaseCommand):
    help = "Seed Psychology Atlas educational content without deleting user-owned data."

    @transaction.atomic
    def handle(self, *args, **options):
        dsm_catalog_active = DSMCorpus.objects.filter(is_active=True).exists()
        category_objs = {}
        for order, (slug, en, fa, description) in enumerate(CATEGORIES):
            obj, _ = Category.objects.get_or_create(
                slug=slug,
                defaults={
                    "name_en": en,
                    "name_fa": fa,
                    "description": description,
                    "sort_order": order,
                    "is_active": not dsm_catalog_active,
                },
            )
            obj.name_en = en
            obj.name_fa = fa
            obj.description = description
            obj.sort_order = order
            if not dsm_catalog_active:
                obj.is_active = True
            obj.save(update_fields=("name_en", "name_fa", "description", "sort_order", "is_active", "updated_at"))
            category_objs[slug] = obj

        disorder_objs = {}
        for item in DISORDERS:
            payload = dict(item)
            seeded_category = category_objs[payload.pop("category")]
            slug = payload.pop("slug")
            existing = Disorder.objects.filter(slug=slug).select_related("category").first()
            preserve_dsm_category = bool(
                dsm_catalog_active
                and existing
                and existing.dsm_master_records.filter(corpus__is_active=True, is_active=True).exists()
            )
            target_category = existing.category if preserve_dsm_category else seeded_category
            obj, _ = Disorder.objects.update_or_create(
                slug=slug,
                defaults={"category": target_category, "is_active": True, **payload},
            )
            disorder_objs[slug] = obj

        if dsm_catalog_active:
            for category in category_objs.values():
                should_be_active = category.disorders.filter(is_active=True).exists()
                if category.is_active != should_be_active:
                    category.is_active = should_be_active
                    category.save(update_fields=("is_active", "updated_at"))

        symptom_objs = {}
        for slug, en, fa, domain in SYMPTOMS:
            symptom, _ = Symptom.objects.update_or_create(
                slug=slug,
                defaults={"name_en": en, "name_fa": fa, "domain": domain},
            )
            symptom_objs[slug] = symptom

        for disorder_slug, symptom_slugs in DISORDER_SYMPTOMS.items():
            for order, symptom_slug in enumerate(symptom_slugs):
                DisorderSymptom.objects.update_or_create(
                    disorder=disorder_objs[disorder_slug],
                    symptom=symptom_objs[symptom_slug],
                    defaults={"prominence": "common", "sort_order": order},
                )

        for source_slug, target_slug, kind, explanation in RELATIONS:
            DifferentialRelationship.objects.update_or_create(
                disorder=disorder_objs[source_slug],
                related_disorder=disorder_objs[target_slug],
                relationship_type=kind,
                defaults={"explanation": explanation},
            )

        source_rows = [
            ("NIMH Mental Health Information", "National Institute of Mental Health", "https://www.nimh.nih.gov/health/topics"),
            ("WHO Mental Health", "World Health Organization", "https://www.who.int/health-topics/mental-health"),
        ]
        source_objs = []
        for title, organization, url in source_rows:
            source, _ = SourceReference.objects.update_or_create(
                title=title,
                organization=organization,
                defaults={"url": url, "source_type": "institutional"},
            )
            source_objs.append(source)
        for item in disorder_objs.values():
            for source in source_objs:
                DisorderSource.objects.get_or_create(disorder=item, source=source)

        for quiz_data in QUIZZES:
            quiz, _ = Quiz.objects.update_or_create(
                slug=quiz_data["slug"],
                defaults={
                    "title": quiz_data["title"],
                    "description": quiz_data["description"],
                    "disorder": disorder_objs[quiz_data["disorder"]],
                    "is_active": True,
                    "seed_managed": True,
                },
            )
            for q_order, (prompt, correct_text, choices, explanation) in enumerate(quiz_data["questions"], start=1):
                question = QuizQuestion.objects.filter(quiz=quiz, sort_order=q_order).order_by("id").first()
                if question:
                    question.prompt = prompt
                    question.explanation = explanation
                    question.is_active = True
                    question.save(update_fields=("prompt", "explanation", "is_active", "updated_at"))
                else:
                    question = QuizQuestion.objects.create(
                        quiz=quiz,
                        prompt=prompt,
                        explanation=explanation,
                        sort_order=q_order,
                        is_active=True,
                    )
                active_choice_orders = []
                for choice_order, text in enumerate(choices, start=1):
                    active_choice_orders.append(choice_order)
                    choice = QuizChoice.objects.filter(question=question, sort_order=choice_order).order_by("id").first()
                    values = {
                        "text": text,
                        "is_correct": text == correct_text,
                        "sort_order": choice_order,
                        "is_active": True,
                    }
                    if choice:
                        choice.text = values["text"]
                        choice.is_correct = values["is_correct"]
                        choice.is_active = True
                        choice.save(update_fields=("text", "is_correct", "sort_order", "is_active"))
                    else:
                        QuizChoice.objects.create(question=question, **values)
                question.choices.exclude(sort_order__in=active_choice_orders).update(is_active=False, is_correct=False)
            quiz.questions.exclude(sort_order__in=range(1, len(quiz_data["questions"]) + 1)).update(is_active=False)

        Quiz.objects.filter(seed_managed=True).exclude(slug__in=[row["slug"] for row in QUIZZES]).update(is_active=False)

